// 展場模式下的語音分流。
//
// 在攤位上，你剛跟人聊完、對方走開，最自然的動作是按住麥克風講一句
// 「這家做精密車床，想找自動化」。這句話應該直接變成剛掃那張名片的筆記，
// 而不是要你先講「筆記 王大明 ...」。
//
// 但「結束展場模式」「現在掃幾張」這類話還是得送去 agent，所以需要分流。
//
// ⚠️ 誤判代價不對稱，這決定了規則要寫多鬆：
//   筆記被當成指令 → 現場觀察直接遺失，你事後不會發現（嚴重）
//   指令被當成筆記 → 多一則沒用的筆記，你看到回覆就知道，再講一次即可（輕微）
// 所以預設一律當筆記，只有「整句明顯就是在對特助下指令」才判為指令。
// 加新規則時請沿用這個保守原則，不要為了方便而放寬成子字串比對。

export type ExpoVoiceIntent = 'note' | 'command'

const COMMAND_PATTERNS: RegExp[] = [
  // 展場模式本身的操作。這些詞不會出現在名片筆記裡，可以寬鬆比對。
  /(結束|關閉|離開|退出)展場|展場(結束|關掉|關了)|收攤|撤攤/,
  /掃了?幾張|幾張了|展場狀態|還在展場/,
  /展場(的)?(戰果|報告)|戰果報告/,

  // 其餘一律要求「整句就是指令」，避免把筆記內容誤判。
  // 例如筆記「找時間再約他喝咖啡」不該被當成搜尋指令，所以搜尋目標限制在 6 字以內
  //（人名或公司名都很短；展場要搜尋用圖文選單的 🔍 更快）。
  /^(找|查|搜尋)\s*\S{1,6}$/,
  /^(待)?跟進(名單|清單)?$/,
  /^(誰要跟進|該聯絡誰|今天要跟進誰)[？?]?$/,
  /^(人脈)?統計$/,
  /^(今天|明天|後天|下週|這週)(的)?(行程|行事曆)[？?]?$/,
  /^業務(進度|戰情)$/,
  /^(匯出|下載)\S*$/,
  /^(幫我寫|起草)/,
]

/**
 * 判斷展場模式下的語音該當成筆記還是指令。
 * 預設 'note'；只有整句明確符合指令樣式才回 'command'。
 */
export function classifyExpoVoice(transcript: string): ExpoVoiceIntent {
  const t = transcript.trim()
  if (!t) return 'command' // 空字串交給 agent 回「聽不清楚」
  return COMMAND_PATTERNS.some(p => p.test(t)) ? 'command' : 'note'
}
